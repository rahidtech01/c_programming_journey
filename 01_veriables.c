#include<stdio.h>

int main() {
    int a = 10; // Integer variable
    float b = 5.5; // Float variable
    char c = 'A'; // Character variable

    printf("Integer: %d\n", a);
    printf("Float: %.2f\n", b);
    printf("Character: %c\n", c);
    printf("The difference between a and b is: %.2f\n", a - b);
    return 0;
}
