/* Out of 3 type of instruction
    type declaration instruction is one of them*/

#include <stdio.h>

int main()
{
    int a;   // declare an integer variable
    float b; // declare an float variable
    char c;  // declare an char variable
    // %d,%f,%c are the format specifier
    // %d is for int,%f is for float,%c is for char
}